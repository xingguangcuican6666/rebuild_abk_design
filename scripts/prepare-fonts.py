#!/usr/bin/env python3
"""Derive the bundled ABK fonts from the upstream LXGW releases.

Yozai (悠哉字体) is the UI family: a softer hand-written Han face than WenKai's
brush-flavoured Kai. WenKai Mono stays the mono role because Yozai mono is thin.

The upstream release files are 15 MB each, so both families are subset here to
GB2312 level 1 plus every character the web catalog and the sample app actually
render, which keeps the AAR and APK sizes honest. The TTF is what Compose loads;
the woff2 faces serve the web catalog with unicode-range slices.

Requires fontTools (and brotli for woff2). Inputs come from `build/font-src` or
`--src`; nothing is downloaded, so a rebuild stays deterministic.
"""
import argparse
import glob
import json
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
NATIVE_DIR = ROOT / "abk-ui/src/main/res/font"
WEB_DIR = ROOT / "assets/fonts/yozai"
LICENSE_DIR = ROOT / "abk-ui/src/main/assets/abk/licenses"
FONTS_JSON = ROOT / "abk-ui/src/main/assets/abk/fonts.json"

# role -> (upstream file, Compose resource name, CSS family weight)
FAMILY = [
    ("Yozai-Regular.ttf", "abk_yozai_regular", 400),
    ("Yozai-Medium.ttf", "abk_yozai_medium", 500),
]
Yozai_VERSION = "v0.868"
Yozai_BASE = f"https://github.com/lxgw/yozai-font/releases/download/{Yozai_VERSION}"

# GB2312 level 1 covers everyday Simplified Chinese; anything outside it in the
# catalog is picked up below, and the fallback chain still has the system font.
LEVEL1_ROWS = range(0xB0, 0xD8)


def gb2312_level1():
    chars = set()
    for high in LEVEL1_ROWS:
        for low in range(0xA1, 0xFF):
            try:
                chars.add(bytes([high, low]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def used_chars():
    chars = set()
    for name in ["index.html"]:
        chars |= set((ROOT / name).read_text(encoding="utf-8"))
    for pattern in ["assets/js/*.js", "assets/css/*.css", "catalog/src/main/**/*.kt",
                    "catalog/src/main/res/**/*.xml", "abk-ui/src/main/kotlin/**/*.kt"]:
        for path in glob.glob(str(ROOT / pattern), recursive=True):
            chars |= set(Path(path).read_text(encoding="utf-8"))
    return chars


def latin_points():
    return (list(range(0x20, 0x7F)) + [0xA0, 0xB0, 0xB7, 0xD7, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D,
                                       0x2022, 0x2026, 0x2191, 0x2193, 0xFFFD])


def han_points():
    return [ord(c) for c in gb2312_level1() | used_chars() if ord(c) > 0x7F] + [0x3000, 0x3001, 0x3002]


def subset(source: Path, unicodes, flavor: str, dest: Path):
    options = Options()
    options.flavor = flavor
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    options.notdef_outline = True
    options.recalc_bounds = True
    options.drop_tables += ["morx", "feat"]  # Apple-only tables fontTools cannot subset
    font = TTFont(source)
    subsetter = Subsetter(options=options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    dest.parent.mkdir(parents=True, exist_ok=True)
    font.save(dest)
    font.close()
    return dest.stat().st_size


def css_ranges(unicodes):
    """Collapse a codepoint list into a CSS unicode-range for the sliced web faces."""
    points = sorted(set(unicodes))
    runs, start, prev = [], points[0], points[0]
    for point in points[1:]:
        if point == prev + 1:
            prev = point
            continue
        runs.append((start, prev))
        start = prev = point
    runs.append((start, prev))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def face(weight, style, family, src, unicode_range):
    return (f"/* {family} · weight {weight} · generated by scripts/prepare-fonts.py */\n"
            f"@font-face {{\n"
            f"  font-family: \"{family}\";\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            f"  font-display: swap;\n"
            f"  src: url(\"./{src}\") format(\"woff2\");\n"
            f"  unicode-range: {unicode_range};\n"
            f"}}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, default=ROOT / "build/font-src",
                        help="directory holding Yozai-Regular.ttf and Yozai-Medium.ttf")
    args = parser.parse_args()

    latin, han = latin_points(), han_points()
    points = latin + han
    css = ["/* ==========================================================================\n"
           "   ABK UI · 悠哉字体（Yozai）\n"
           "   由 scripts/prepare-fonts.py 生成，不要手改。两个字重各两个切片共用同一家族：\n"
           "   latin 只含 ASCII 与常用标点，han 含 GB2312 一级汉字与目录里出现的字。\n"
           "   ========================================================================== */"]
    entries = {}
    for upstream, resource, weight in FAMILY:
        source = args.src / upstream
        ttf = NATIVE_DIR / f"{resource}.ttf"
        size = subset(source, points, "none", ttf)
        print(f"{ttf.relative_to(ROOT)}: {size} bytes")
        for label, slice_points in (("latin", latin), ("han", han)):
            subset(source, slice_points, "woff2", WEB_DIR / f"ABK-Yozai-{weight}-{label}.woff2")
            css.append(face(weight, "normal", "Yozai", f"ABK-Yozai-{weight}-{label}.woff2",
                            css_ranges(slice_points)))
        entries[f"{resource}.ttf"] = {
            "url": f"{Yozai_BASE}/{upstream}",
            "license": "OFL 1.1 · abk/licenses/OFL-yozai.txt",
            "family-name": "Yozai (not renamed: SIL OFL reserved font name applies to the source)",
            "subset": "GB2312 level 1 + characters used by the web catalog and the sample app",
            "bytes": size,
        }
    (ROOT / "assets/css/fonts-yozai.css").write_text("\n".join(css), encoding="utf-8")
    FONTS_JSON.write_text(json.dumps({
        "version": Yozai_VERSION,
        "files": entries,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("wrote assets/css/fonts-yozai.css and fonts.json")


if __name__ == "__main__":
    main()
